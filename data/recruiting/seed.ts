function postingFromRequisition(
  requisition: JobRequisition,
  slug: string,
  publishedAt: string,
  departmentName: string,
  locationName: string,
): Job {
  return {
    id: `post-${requisition.id}`,
    requisitionId: requisition.id,
    slug,
    title: requisition.title,
    summary: requisition.description,
    description: `This is a sample position for development and design review. ${requisition.description}`,
    careerArea: requisition.careerArea,
    departmentName,
    locationName,
    workplaceType: requisition.workplaceType,
    employmentType: requisition.employmentType,
    responsibilities: requisition.responsibilities,
    qualifications: requisition.qualifications,
    preferredQualifications: requisition.preferredQualifications,
    status: "PUBLISHED",
    publishedAt,
    isDemo: true,
    createdAt: now,
    updatedAt: now,
  };
}

